/** Sample once at the server page boundary so hydration keeps the same identities. */
export function selectFishCompanies(random: () => number = Math.random): FishCompany[] {
  const pool = [...FISH_COMPANIES];
  for (let index = 0; index < FISH_SCHOOL_SIZE; index++) {
    const selected = index + Math.floor(random() * (pool.length - index));
    [pool[index], pool[selected]] = [pool[selected], pool[index]];
  }
  return pool.slice(0, FISH_SCHOOL_SIZE);
}
